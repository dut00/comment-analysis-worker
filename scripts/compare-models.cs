// Side-by-side comparison of decision models on the labelled comments in tests/data, from results saved by
// scripts/quality-report.cs (no model is queried).
//
//   dotnet run scripts/compare-models.cs -- <comments.json> <comparison.md> <name>=<results.json> [<name>=<results.json> ...]
//
// Every model is decided with the current default policy (DecisionPolicyOptions), so the comparison follows the policy
// the worker ships with. The policy helpers mirror those of quality-report.cs.
using System.Globalization;
using System.Text;
using System.Text.Json;
using CommentAnalysis.Core.Decisions;
using CommentAnalysis.Core.Models;

if (args.Length < 4 || args[2..].Any(arg => !arg.Contains('=', StringComparison.Ordinal)))
{
    Console.Error.WriteLine("Usage: compare-models.cs <comments.json> <comparison.md> <name>=<results.json> <name>=<results.json> [...]");
    return 1;
}

var json = new JsonSerializerOptions(JsonSerializerDefaults.Web);
var samples = JsonSerializer.Deserialize<SampleFile>(File.ReadAllText(args[0]), json)!.Comments;
var models = args[2..]
    .Select(arg => arg.Split('=', 2))
    .Select(parts => new Model(
        parts[0],
        JsonSerializer.Deserialize<List<Result>>(File.ReadAllText(parts[1]), json)!.ToDictionary(result => result.Id, StringComparer.Ordinal)))
    .ToList();

File.WriteAllText(args[1], Compare(samples, models).ReplaceLineEndings("\n"));
Console.WriteLine($"Comparison: {args[1]}");
return 0;

static string Compare(IReadOnlyList<Sample> samples, IReadOnlyList<Model> models)
{
    var policy = new DecisionPolicyOptions();
    var report = new StringBuilder();
    string Cell(FormattableString value) => value.ToString(CultureInfo.InvariantCulture);

    report.AppendLine("# Decision model comparison");
    report.AppendLine();
    report.AppendLine(Cell($"The same {samples.Count} labelled Polish comments (`tests/data/polish-comments.json`) and the same four questions, decided with the default policy: approve ≥ {policy.ApproveThreshold}, reject ≥ {policy.RejectThreshold}, toxicity ≤ {policy.MaxToxicityForApprove}, spam ≤ {policy.MaxSpamForApprove}, personal data ≤ {policy.MaxPersonalDataForApprove}. Generated by `scripts/compare-models.cs` from the saved results; the per-model reports are next to this file."));
    report.AppendLine();
    report.AppendLine("Model versions:");
    report.AppendLine();
    foreach (var model in models)
    {
        report.AppendLine(Cell($"- {model.Name}: `{string.Join("`, `", model.Results.Values.Select(result => result.ModelVersion).Distinct())}`"));
    }

    var decided = models.ToDictionary(
        model => model.Name,
        model => samples.ToDictionary(
            sample => sample.Id,
            sample => model.Results.TryGetValue(sample.Id, out var result) && result.Error is null ? Decide(result, policy) : null));

    report.AppendLine();
    report.AppendLine("## Summary");
    report.AppendLine();
    report.AppendLine(Cell($"| | {string.Join(" | ", models.Select(model => model.Name))} |"));
    report.AppendLine(Cell($"|---|{string.Concat(models.Select(_ => "---|"))}"));
    void Row(string metric, Func<Model, string> value) =>
        report.AppendLine(Cell($"| {metric} | {string.Join(" | ", models.Select(value))} |"));
    int CountWhere(Model model, Func<Sample, Decision, bool> predicate) =>
        samples.Count(sample => decided[model.Name][sample.Id] is { } decision && predicate(sample, decision.Decision));

    Row("Evaluated", model => Cell($"{samples.Count(sample => decided[model.Name][sample.Id] is not null)} of {samples.Count}"));
    Row("**Decision as expected**", model => Cell($"**{CountWhere(model, (sample, decision) => Matches(sample.Expected, decision))}**"));
    Row("Verdict label right (clear cases)", model =>
    {
        // Over the evaluated comments only, as in quality-report.cs.
        var clear = samples.Where(sample => sample.Expected is "approve" or "reject" && decided[model.Name][sample.Id] is not null).ToList();
        var right = clear.Count(sample => model.Results[sample.Id].Label == (sample.Expected == "approve" ? ContentLabel.Acceptable : ContentLabel.Unacceptable));
        return Cell($"{right} of {clear.Count}");
    });
    Row("Wrongly approved", model => CountWhere(model, (sample, decision) => sample.Expected != "approve" && decision == Decision.Approve).ToString(CultureInfo.InvariantCulture));
    Row("Wrongly rejected", model => CountWhere(model, (sample, decision) => sample.Expected != "reject" && decision == Decision.Reject).ToString(CultureInfo.InvariantCulture));
    Row("Manual reviews", model => CountWhere(model, (_, decision) => decision == Decision.ManualReview).ToString(CultureInfo.InvariantCulture));
    Row("Latency per comment (median / max)", model =>
    {
        var seconds = samples
            .Where(sample => decided[model.Name][sample.Id] is not null)
            .Select(sample => model.Results[sample.Id].Seconds)
            .Order()
            .ToList();
        return seconds.Count == 0 ? "–" : Cell($"{seconds[seconds.Count / 2]:F1} s / {seconds[^1]:F1} s");
    });

    report.AppendLine();
    report.AppendLine("## Decisions");
    report.AppendLine();
    report.AppendLine("Decision and confidence of the verdict; ✗ marks a decision other than expected, and **bold** ids the comments on which the models disagree.");
    report.AppendLine();
    report.AppendLine(Cell($"| id | category | expected | {string.Join(" | ", models.Select(model => model.Name))} |"));
    report.AppendLine(Cell($"|---|---|---|{string.Concat(models.Select(_ => "---|"))}"));
    foreach (var sample in samples)
    {
        var decisions = models.Select(model => decided[model.Name][sample.Id]).ToList();
        var differ = decisions.Select(decision => decision?.Decision).Distinct().Count() > 1;
        var cells = models.Select(model =>
        {
            if (decided[model.Name][sample.Id] is not { } decision)
            {
                return "failed";
            }

            var mark = Matches(sample.Expected, decision.Decision) ? "" : " ✗";
            var reasons = decision.ReviewReasons.Count > 0 ? Cell($" ({string.Join(", ", decision.ReviewReasons)})") : "";
            return Cell($"{decision.Decision}{mark} {model.Results[sample.Id].Confidence:F2}{reasons}");
        });
        var id = differ ? $"**{sample.Id}**" : sample.Id;
        report.AppendLine(Cell($"| {id} | {sample.Category} | {sample.Expected} | {string.Join(" | ", cells)} |"));
    }

    report.AppendLine();
    report.AppendLine("## Signals");
    report.AppendLine();
    report.AppendLine("Toxicity / spam / personal data, each in [0, 1]; an approval needs them at or below the limits above.");
    report.AppendLine();
    report.AppendLine(Cell($"| id | {string.Join(" | ", models.Select(model => model.Name))} |"));
    report.AppendLine(Cell($"|---|{string.Concat(models.Select(_ => "---|"))}"));
    foreach (var sample in samples)
    {
        var cells = models.Select(model => model.Results.TryGetValue(sample.Id, out var result) && result.Error is null
            ? Cell($"{result.Toxicity:F2} / {result.Spam:F2} / {result.PersonalData:F2}")
            : "–");
        report.AppendLine(Cell($"| {sample.Id} | {string.Join(" | ", cells)} |"));
    }

    return report.ToString();
}

static PolicyDecision Decide(Result result, DecisionPolicyOptions options) =>
    new DecisionPolicy(options).Decide(new ModelPrediction(
        result.Label!.Value,
        result.Confidence!.Value,
        signals: new ModerationSignals(result.Toxicity!.Value, result.Spam!.Value, result.PersonalData!.Value)));

static bool Matches(string expected, Decision decision) => expected switch
{
    "approve" => decision == Decision.Approve,
    "reject" => decision == Decision.Reject,
    _ => decision == Decision.ManualReview,
};

internal sealed record Model(string Name, IReadOnlyDictionary<string, Result> Results);

internal sealed record SampleFile(IReadOnlyList<Sample> Comments);

internal sealed record Sample(string Id, string Category, string Expected, string Content);

internal sealed record Result(
    string Id,
    string ModelVersion,
    ContentLabel? Label,
    double? Confidence,
    double? Toxicity,
    double? Spam,
    double? PersonalData,
    double Seconds,
    string? Error);
